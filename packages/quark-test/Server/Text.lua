local Test = Quark.Import("Testing")
local Expect = Test.Expect

Test.Describe("Regex", function()
    local Regex = Quark.Regex

    Test.It("matches with groups and names", function()
        local date = Regex.New("(?P<year>\\d{4})-(?P<month>\\d{2})-(\\d{2})?")
        Expect(date:IsMatch("on 2026-10-")):ToBe(true)
        local found = date:Match("released 2026-10-25!")
        Expect(found.Text):ToBe("2026-10-25")
        Expect(found.Start):ToBe(10)
        Expect(found.End):ToBe(19)
        Expect(found.Groups):ToEqual({ "2026", "10", "25" })
        Expect(found.Named):ToEqual({ year = "2026", month = "10" })
        Expect(date:Match("x 2026-10-").Groups[3]):ToBe(false)
        Expect(date:GetGroupNames()):ToEqual({ "year", "month" })
        Expect(date:GetGroupCount()):ToBe(3)
    end)

    Test.It("finds like string.find", function()
        local start, finish, text = Regex.Find("\\w+", "  hello world", 1)
        Expect({ start, finish, text }):ToEqual({ 3, 7, "hello" })
        Expect(Regex.Find("\\w+", "  hello world", 8)):ToBe(9)
        Expect(Regex.Find("x", "abc")):ToBeNil()
        Expect(Regex.IsMatch("^a", "abc", 2)):ToBe(false)
    end)

    Test.It("lists all matches and counts", function()
        local numbers = Regex.New("\\d+")
        local matches = numbers:MatchAll("1 22 333")
        Expect(#matches):ToBe(3)
        Expect(matches[3].Text):ToBe("333")
        Expect(numbers:MatchAll("1 22 333", 2)):ToHaveLength(2)
        Expect(numbers:Count("a1b2c3")):ToBe(3)
    end)

    Test.It("replaces with templates, functions and tables", function()
        Expect(Regex.Replace("(\\w+)@(\\w+)", "me@host", "$2 at ${1}")):ToBe("host at me")
        local result, count = Regex.Replace("\\d+", "a1b22c3", function(found)
            return tostring(tonumber(found.Text) * 2)
        end)
        Expect(result):ToBe("a2b44c6")
        Expect(count):ToBe(3)
        Expect(Regex.Replace("\\w+", "red blue", { red = "rot" })):ToBe("rot blue")
        Expect(Regex.Replace("a", "aaa", "b", 2)):ToBe("bba")
        Expect(Regex.Replace("a", "aaa", function() return nil end)):ToBe("aaa")
    end)

    Test.It("splits", function()
        Expect(Regex.Split("\\s*,\\s*", "a , b,c")):ToEqual({ "a", "b", "c" })
        Expect(Regex.Split(",", "a,b,c", 2)):ToEqual({ "a", "b,c" })
    end)

    Test.It("supports options and Unicode", function()
        local word = Regex.New("^straße$", { CaseInsensitive = true })
        Expect(word:IsMatch("STRASSE")):ToBe(false)
        Expect(word:IsMatch("Straße")):ToBe(true)
        Expect(Regex.New("^b", { Multiline = true }):IsMatch("a\nb")):ToBe(true)
        Expect(Regex.New("a.b", { DotAll = true }):IsMatch("a\nb")):ToBe(true)
        Expect(Regex.New("a b # comment", { Extended = true }):IsMatch("ab")):ToBe(true)
        Expect(Regex.Match("\\p{L}+", "123 Ümlaut").Text):ToBe("Ümlaut")
    end)

    Test.It("reports invalid patterns", function()
        local regex, message = Regex.New("(unclosed")
        Expect(regex):ToBeNil()
        Expect(message):ToContain("invalid regular expression")
        Expect(Regex.IsValid("a+")):ToBe(true)
        Expect(Regex.IsValid("(?<=a)b")):ToBe(false)
        Expect(function() Regex.IsMatch("[", "x") end):ToThrow("invalid regular expression")
        Expect(Regex.Escape("1+1=2?")):ToBe("1\\+1=2\\?")
    end)
end)

Test.Describe("Text", function()
    local Text = Quark.Text

    Test.It("handles Unicode case and normalization", function()
        Expect(Text.Upper("straße äö")):ToBe("STRASSE ÄÖ")
        Expect(Text.Lower("ÄÖÜ")):ToBe("äöü")
        Expect(Text.Capitalize("hello wORLD, it's me")):ToBe("Hello World, It's Me")
        Expect(Text.Normalize("e\u{301}")):ToBe("é")
        Expect(#Text.Normalize("é", "NFD")):ToBe(3)
        Expect(Text.ToAscii("Æneid café ü")):ToBe("AEneid cafe u")
        Expect(Text.Slugify("  Hello, Wörld! 2026 ")):ToBe("hello-world-2026")
        Expect(Text.Slugify("A B", "_")):ToBe("a_b")
        Expect(Text.IsValid("ok")):ToBe(true)
        Expect(Text.IsValid("\xff")):ToBe(false)
    end)

    Test.It("counts and cuts graphemes", function()
        local family = "👨‍👩‍👧"
        Expect(Text.Length("a" .. family .. "é")):ToBe(3)
        Expect(Text.Graphemes("a" .. family)):ToEqual({ "a", family })
        Expect(Text.Sub("héllo", 2, 3)):ToBe("él")
        Expect(Text.Sub("héllo", -2)):ToBe("lo")
        Expect(Text.Reverse("añb")):ToBe("bña")
        Expect(Text.Truncate("Hello World", 8)):ToBe("Hello...")
        Expect(Text.Truncate("Hello", 8)):ToBe("Hello")
        Expect(Text.Truncate("Hello World", 2)):ToBe("He")
        Expect(Text.Words("Hello, world! It's 5pm.")):ToEqual({ "Hello", "world", "It's", "5pm" })
    end)

    Test.It("splits, trims, pads and wraps", function()
        Expect(Text.Split("a,b,,c", ",")):ToEqual({ "a", "b", "", "c" })
        Expect(Text.Split("a, b,,c", ",", { Trim = true, RemoveEmpty = true })):ToEqual({ "a", "b", "c" })
        Expect(Text.Split("a.b.c", ".", { Limit = 2 })):ToEqual({ "a", "b.c" })
        Expect(Text.Split("äb", "")):ToEqual({ "ä", "b" })
        Expect(Text.Trim("  x \n")):ToBe("x")
        Expect(Text.Pad("ä", 3)):ToBe("ä  ")
        Expect(Text.Pad("7", 3, { Align = "Right", Char = "0" })):ToBe("007")
        Expect(Text.Pad("ab", 6, { Align = "Center" })):ToBe("  ab  ")
        Expect(Text.Wrap("the quick brown fox", 10)):ToEqual({ "the quick", "brown fox" })
        Expect(Text.Wrap("abcdefghij kl", 4)):ToEqual({ "abcd", "efgh", "ij", "kl" })
    end)

    Test.It("measures similarity", function()
        Expect(Text.Levenshtein("kitten", "sitting")):ToBe(3)
        Expect(Text.DamerauLevenshtein("ab", "ba")):ToBe(1)
        Expect(Text.Similarity("martha", "marhta")):ToBeCloseTo(0.961, 0.001)
        Expect(Text.Similarity("abc", "abc", "Levenshtein")):ToBe(1)
        Expect(function() Text.Similarity("a", "b", "Soundex") end):ToThrow("unknown algorithm")
    end)

    Test.It("finds fuzzy matches", function()
        local players = { "DasDarki", "Darkness", "SyedMuhammad", "Timmy", "darki_fan" }
        local results = Text.FuzzyFind("dark", players)
        Expect(results[1].Item):ToBe("Darkness")
        Expect(results[2].Item):ToBe("darki_fan")
        Expect(results[3].Item):ToBe("DasDarki")
        Expect(results[1].Index):ToBe(2)
        Expect(Text.FuzzyFind("dark", players, { Limit = 1 })):ToHaveLength(1)
        Expect(Text.Closest("timy", players)):ToBe("Timmy")
        Expect(Text.Closest("zzzz", players)):ToBeNil()

        local commands = { { Name = "teleport" }, { Name = "kick" }, { Name = "ban" } }
        Expect(Text.Closest("telport", commands, { Key = "Name" }).Name):ToBe("teleport")
        Expect(function() Text.FuzzyFind("x", commands) end):ToThrow("Key")
    end)
end)

Test.Describe("Text.WordFilter", function()
    local Text = Quark.Text

    Test.It("finds words through leetspeak, case and repeats", function()
        local filter = Text.WordFilter({ "badword", "evil thing" })
        Expect(filter:Contains("this is a B4DW0RD")):ToBe(true)
        Expect(filter:Contains("baaaadwooord!")):ToBe(true)
        Expect(filter:Contains("an EVIL   thing")):ToBe(true)
        Expect(filter:Contains("evil, thing")):ToBe(true)
        Expect(filter:Contains("badwordy")):ToBe(false)
        Expect(filter:Contains("all good")):ToBe(false)

        local found = filter:Find("x B4dword y")
        Expect(found):ToHaveLength(1)
        Expect(found[1]):ToEqual({ Word = "badword", Text = "B4dword", Start = 3, End = 9 })
    end)

    Test.It("censors matches", function()
        local filter = Text.WordFilter({ "darn", "heck" })
        local censored, count = filter:Censor("Darn it, what the h3ck")
        Expect(censored):ToBe("**** it, what the ****")
        Expect(count):ToBe(2)
        Expect(filter:Censor("darn", "[removed]")):ToBe("[removed]")
        Expect(filter:Censor("dárn")):ToBe("****")
    end)

    Test.It("matches inside words without WholeWords", function()
        local filter = Text.WordFilter({ "ass" }, { WholeWords = false, Repeats = false })
        Expect(filter:Contains("classic")):ToBe(true)
        Expect(Text.WordFilter({ "ass" }):Contains("classic")):ToBe(false)
    end)

    Test.It("adds and removes words", function()
        local filter = Text.WordFilter({})
        Expect(filter:Contains("anything")):ToBe(false)
        filter:Add({ "spam", "scam" })
        Expect(filter:Contains("no spam")):ToBe(true)
        filter:Remove({ "spam" })
        Expect(filter:Contains("no spam")):ToBe(false)
        Expect(filter:GetWords()):ToEqual({ "scam" })
    end)
end)

Test.Describe("Template", function()
    local Template = Quark.Template

    Test.It("renders strings", function()
        local text = Template.Render("Hello {{ name }}! {% for item in items %}[{{ item }}]{% endfor %}", { name = "World", items = { 1, 2, 3 } })
        Expect(text):ToBe("Hello World! [1][2][3]")
        Expect(Template.Render("{{ value | upper }} {{ count + 1 }}", { value = "abc", count = 41 })):ToBe("ABC 42")
        Expect(Template.Render("{{ missing }}|")):ToBe("|")
    end)

    Test.It("escapes and reports errors", function()
        Expect(Template.Render("{{ html }}", { html = "<b>" }, { AutoEscape = "Html" })):ToBe("&lt;b&gt;")
        Expect(Template.Render("{{ html }}", { html = "<b>" })):ToBe("<b>")
        local text, message = Template.Render("{% if %}")
        Expect(text):ToBeNil()
        Expect(message):ToContain("syntax error")
        local strict, strict_message = Template.Render("{{ missing }}", {}, { Undefined = "Strict" })
        Expect(strict):ToBeNil()
        Expect(strict_message):ToContain("undefined")
    end)

    Test.It("keeps named templates with inheritance", function()
        local templates = Template.New({
            Templates = {
                base = "<{% block body %}{% endblock %}>",
                page = "{% extends 'base' %}{% block body %}{{ title }}{% endblock %}",
            },
            Globals = { server = "Quark" },
        })
        Expect(templates:Render("page", { title = "Hi" })):ToBe("<Hi>")
        Expect(templates:RenderString("{{ server }}")):ToBe("Quark")
        Expect(templates:Has("page")):ToBe(true)
        Expect(templates:GetNames()):ToEqual({ "base", "page" })
        Expect(templates:Add("broken", "{% for %}")):ToBeNil()
        Expect(templates:Add("welcome", "Welcome {{ name }}")):ToBe(true)
        Expect(templates:Render("welcome", { name = "Ada" })):ToBe("Welcome Ada")
        templates:Remove("welcome")
        local missing, message = templates:Render("welcome")
        Expect(missing):ToBeNil()
        Expect(message):ToContain("not found")
    end)

    Test.It("calls Lua filters, functions and tests", function()
        local text = Template.Render("{{ name | shout }} {{ add(2, 3) }} {% if 4 is even %}even{% endif %} {{ [1, 2] | total }}", { name = "ada" }, {
            Filters = {
                shout = function(value) return value:upper() .. "!" end,
                total = function(list) local sum = 0 for _, value in ipairs(list) do sum = sum + value end return sum end,
            },
            Functions = { add = function(a, b) return a + b end },
            Tests = { even = function(value) return value % 2 == 0 end },
        })
        Expect(text):ToBe("ADA! 5 even 3")

        local templates = Template.New()
        templates:AddFilter("money", function(value, currency) return string.format("%.2f %s", value, currency or "$") end)
        templates:AddFunction("player", function(id) return { Name = "Player " .. id } end)
        templates:Add("price", "{{ 4.5 | money('EUR') }} for {{ player(7).Name }}")
        Expect(templates:Render("price")):ToBe("4.50 EUR for Player 7")

        local failed, message = Template.Render("{{ 1 | broken }}", {}, { Filters = { broken = function() error("nope") end } })
        Expect(failed):ToBeNil()
        Expect(message):ToContain("nope")
    end)

    Test.It("stops runaway templates", function()
        local text, message = Template.Render("{% for a in range(10000) %}{% for b in range(10000) %}{% endfor %}{% endfor %}", {}, { Fuel = 100000 })
        Expect(text):ToBeNil()
        Expect(message):ToContain("fuel")
    end)
end)
