local Test = Quark.Import("Testing")
local Expect = Test.Expect

Test.Describe("Time", function()
    local Time = Quark.Time

    local function utc(year, month, day, hour, minute, second)
        return Time.Date({ Year = year, Month = month, Day = day, Hour = hour, Minute = minute, Second = second }, "UTC")
    end

    Test.It("creates dates with fields", function()
        local date = utc(2026, 1, 1)
        Expect(date:GetUnixMs()):ToBe(1767225600000)
        Expect(date:GetUnix()):ToBe(1767225600)
        Expect(date.Year):ToBe(2026)
        Expect(date.Weekday):ToBe(4)
        Expect(date.YearDay):ToBe(1)
        Expect(date.Zone):ToBe("UTC")
        Expect(date:ToTable()):ToEqual({ Year = 2026, Month = 1, Day = 1, Hour = 0, Minute = 0, Second = 0, Millisecond = 0, Weekday = 4, YearDay = 1, Zone = "UTC", Offset = 0 })
        Expect(Time.FromUnixMs(1767225600000, "UTC") == date):ToBe(true)
        Expect(Time.FromUnix(1767225600.5, "UTC").Millisecond):ToBe(500)
        Expect(function() Time.Date({ Year = 2026, Month = 2, Day = 30 }) end):ToThrow()
    end)

    Test.It("knows the current time", function()
        local now = Time.Now("UTC")
        Expect(math.abs(now:GetUnixMs() - Time.UnixMs())):ToBeLessThan(1000)
        Expect(math.abs(Time.Unix() - os.time())):ToBeLessThan(2)
        Expect(Time.IsDateTime(now)):ToBe(true)
        Expect(Time.IsDateTime({})):ToBe(false)
        Expect(Time.Now():GetUnixMs()):ToBeGreaterThan(0)
    end)

    Test.It("converts time zones", function()
        local noon = utc(2026, 1, 1, 12)
        local tokyo = noon:InZone("Asia/Tokyo")
        Expect(tokyo.Hour):ToBe(21)
        Expect(tokyo.Offset):ToBe(9 * 3600)
        Expect(tokyo == noon):ToBe(true)
        Expect(tokyo:ToUTC().Hour):ToBe(12)
        Expect(Time.Date({ Year = 2026, Month = 10, Day = 25, Hour = 12 }, "Europe/Berlin"):ToISO()):ToBe("2026-10-25T12:00:00+01:00")
        Expect(Time.IsValidZone("America/New_York")):ToBe(true)
        Expect(Time.IsValidZone("Mars/Base")):ToBe(false)
        Expect(function() Time.Now("Mars/Base") end):ToThrow("unknown time zone")
        Expect(Time.GetZones()):ToContain("Europe/Berlin")
        Expect(Time.GetSystemZone()):ToBeType("string")
    end)

    Test.It("parses dates", function()
        local offset = Time.Parse("2026-06-01T10:00:00+02:00")
        Expect(offset.Hour):ToBe(10)
        Expect(offset.Offset):ToBe(7200)
        Expect(offset:GetUnixMs()):ToBe(1780300800000)
        Expect(Time.Parse("2026-06-01T08:00:00Z") == offset):ToBe(true)
        Expect(Time.Parse("2026-06-01T10:00:00+02:00[Europe/Berlin]").Zone):ToBe("Europe/Berlin")
        Expect(Time.Parse("2026-06-01T08:00:00Z", { Zone = "Europe/Berlin" }).Hour):ToBe(10)

        local civil = Time.Parse("2026-06-01 10:00", { Zone = "UTC" })
        Expect({ civil.Hour, civil.Zone }):ToEqual({ 10, "UTC" })
        local date = Time.Parse("2026-06-01", { Zone = "America/New_York" })
        Expect({ date.Hour, date.Offset }):ToEqual({ 0, -14400 })

        Expect(Time.Parse("Mon, 01 Jun 2026 10:00:00 +0000").Hour):ToBe(10)
        local custom = Time.Parse("24.12.2026 18:30", { Format = "%d.%m.%Y %H:%M", Zone = "Europe/Berlin" })
        Expect({ custom.Day, custom.Hour, custom.Offset }):ToEqual({ 24, 18, 3600 })

        local invalid, message = Time.Parse("nonsense")
        Expect(invalid):ToBeNil()
        Expect(message):ToContain("date format")
    end)

    Test.It("formats dates", function()
        local date = utc(2026, 6, 1, 8, 5, 3)
        Expect(date:Format("%Y-%m-%d %H:%M:%S")):ToBe("2026-06-01 08:05:03")
        Expect(date:Format("%A, %B %-d")):ToBe("Monday, June 1")
        Expect(date:ToISO()):ToBe("2026-06-01T08:05:03+00:00")
        Expect(date:ToRFC2822()):ToBe("Mon, 1 Jun 2026 08:05:03 +0000")
        Expect(tostring(date)):ToBe("2026-06-01T08:05:03+00:00[UTC]")
    end)

    Test.It("calculates with calendars and time zones", function()
        local before = Time.Date({ Year = 2026, Month = 3, Day = 29, Hour = 1, Minute = 30 }, "Europe/Berlin")
        local later = before:Add("1h")
        Expect({ later.Hour, later.Offset }):ToEqual({ 3, 7200 })
        local next_day = before:Add({ Days = 1 })
        Expect({ next_day.Day, next_day.Hour }):ToEqual({ 30, 1 })
        Expect(before:Add(90000).Minute):ToBe(31)
        Expect(utc(2026, 1, 31):Add({ Months = 1 }).Day):ToBe(28)
        Expect(utc(2026, 1, 1):Subtract("1 day").Year):ToBe(2025)

        Expect(utc(2026, 3, 1):Since(utc(2026, 1, 1))):ToBe(59 * 86400000)
        Expect(utc(2026, 3, 1):Since(utc(2026, 1, 1), "Months")):ToBe(2)
        Expect(utc(2026, 3, 1):Since(utc(2026, 1, 1), "Days")):ToBe(59)
        Expect(utc(2026, 1, 1, 1, 30):Since(utc(2026, 1, 1), "Hours")):ToBe(1.5)

        Expect(utc(2026, 1, 1, 15, 20):StartOf("Week"):ToISO()):ToBe("2025-12-29T00:00:00+00:00")
        local month_end = utc(2026, 2, 10):EndOf("Month")
        Expect({ month_end.Day, month_end.Hour, month_end.Millisecond }):ToEqual({ 28, 23, 999 })
        Expect(utc(2026, 5, 5, 10, 45):StartOf("Hour").Minute):ToBe(0)
        Expect(utc(2026, 5, 5, 10, 45):With({ Hour = 5, Day = 1 }):ToISO()):ToBe("2026-05-01T05:45:00+00:00")
    end)

    Test.It("compares and describes relative times", function()
        local now = utc(2026, 1, 1, 12)
        Expect(now < now:Add(1)):ToBe(true)
        Expect(now <= now:Add(0)):ToBe(true)
        Expect(now:IsBefore(now:Add(1))):ToBe(true)
        Expect(now:IsAfter(now:Add(1))):ToBe(false)
        Expect(now:Add("3h"):Relative(now)):ToBe("in 3 hours")
        Expect(now:Subtract("2d"):Relative(now)):ToBe("2 days ago")
        Expect(now:Subtract("1m"):Relative(now)):ToBe("1 minute ago")
        Expect(now:Add(10000):Relative(now)):ToBe("just now")
        Expect(now:Add({ Years = 2 }):Relative(now)):ToBe("in 2 years")
    end)

    Test.It("parses and formats durations", function()
        Expect(Time.ParseDuration("1h 30m")):ToBe(5400000)
        Expect(Time.ParseDuration("2d")):ToBe(172800000)
        Expect(Time.ParseDuration("90s")):ToBe(90000)
        Expect(Time.ParseDuration("PT1M30S")):ToBe(90000)
        Expect(Time.ParseDuration("1 week")):ToBe(604800000)
        Expect(Time.ParseDuration("1.5h")):ToBe(5400000)
        Expect(Time.ParseDuration("2 days 3 hours")):ToBe(183600000)
        local months, message = Time.ParseDuration("1 month")
        Expect(months):ToBeNil()
        Expect(message):ToContain("months")
        Expect(Time.ParseDuration("garbage")):ToBeNil()

        Expect(Time.FormatDuration(5400000)):ToBe("1h 30m")
        Expect(Time.FormatDuration(5400000, { Style = "Long" })):ToBe("1 hour, 30 minutes")
        Expect(Time.FormatDuration(93784000)):ToBe("1d 2h 3m 4s")
        Expect(Time.FormatDuration(93784000, { Largest = 2, Style = "Long" })):ToBe("1 day, 2 hours")
        Expect(Time.FormatDuration(3725000, { Style = "Clock" })):ToBe("1:02:05")
        Expect(Time.FormatDuration(65000, { Style = "Clock" })):ToBe("1:05")
        Expect(Time.FormatDuration(0)):ToBe("0s")
        Expect(Time.FormatDuration(500)):ToBe("500ms")
        Expect(Time.FormatDuration(-60000)):ToBe("-1m")
        Expect(Time.FormatDuration("2h")):ToBe("2h")
    end)
end)

Test.Describe("Time.Cron", function()
    local Time = Quark.Time

    local function utc(year, month, day, hour, minute, second)
        return Time.Date({ Year = year, Month = month, Day = day, Hour = hour, Minute = minute, Second = second }, "UTC")
    end

    Test.It("finds the next times", function()
        local office = Time.Cron("*/15 9-17 * * MON-FRI", { Zone = "UTC" })
        local friday_evening = utc(2026, 1, 2, 17, 50)
        Expect(office:Next(friday_evening):ToISO()):ToBe("2026-01-05T09:00:00+00:00")
        local times = office:NextMany(3, friday_evening)
        Expect({ times[1].Minute, times[2].Minute, times[3].Minute }):ToEqual({ 0, 15, 30 })
        Expect(office:Matches(utc(2026, 1, 5, 9, 15))):ToBe(true)
        Expect(office:Matches(utc(2026, 1, 4, 9, 15))):ToBe(false)
        Expect(office:GetExpression()):ToBe("*/15 9-17 * * MON-FRI")
        Expect(office:GetZone()):ToBe("UTC")
    end)

    Test.It("supports macros, seconds and special days", function()
        Expect(Time.Cron("@daily", { Zone = "UTC" }):Next(utc(2026, 1, 1, 12)):ToISO()):ToBe("2026-01-02T00:00:00+00:00")
        Expect(Time.Cron("30 * * * * *", { Zone = "UTC" }):Next(utc(2026, 1, 1, 12)).Second):ToBe(30)
        Expect(Time.Cron("0 0 L * *", { Zone = "UTC" }):Next(utc(2026, 2, 10)).Day):ToBe(28)
        Expect(Time.Cron("0 0 13 * FRI", { Zone = "UTC" }):Next(utc(2026, 1, 1)).Day):ToBe(2)
        Expect(Time.Cron("0 0 * * 7", { Zone = "UTC" }):Next(utc(2026, 1, 1)).Weekday):ToBe(7)
        Expect(Time.Cron("0 0 1 JAN *", { Zone = "UTC" }):Next(utc(2026, 1, 1)).Year):ToBe(2027)
        Expect(Time.Cron("0 0 30 2 *", { Zone = "UTC" }):Next(utc(2026, 1, 1))):ToBeNil()
    end)

    Test.It("handles daylight saving time", function()
        local nightly = Time.Cron("30 2 * * *", { Zone = "Europe/Berlin" })
        local skipped = nightly:Next(Time.Date({ Year = 2026, Month = 3, Day = 28, Hour = 12 }, "Europe/Berlin"))
        Expect({ skipped.Day, skipped.Hour, skipped.Minute }):ToEqual({ 29, 3, 30 })
        local after = nightly:Next(skipped)
        Expect({ after.Day, after.Hour }):ToEqual({ 30, 2 })

        local repeated = nightly:NextMany(2, Time.Date({ Year = 2026, Month = 10, Day = 24, Hour = 12 }, "Europe/Berlin"))
        Expect({ repeated[1].Day, repeated[1].Hour, repeated[2].Day }):ToEqual({ 25, 2, 26 })
    end)

    Test.It("rejects invalid expressions", function()
        local cron, message = Time.Cron("61 * * * *")
        Expect(cron):ToBeNil()
        Expect(message):ToContain("outside")
        Expect(select(2, Time.Cron("* * *"))):ToContain("5 or 6 fields")
        Expect(select(2, Time.Cron("*/0 * * * *"))):ToContain("at least 1")
        Expect(select(2, Time.Cron("@sometimes"))):ToContain("unknown cron macro")
        Expect(select(2, Time.Cron("* * * FOO *"))):ToContain("not a number")
    end)

    Test.It("runs schedules", function()
        local calls = {}
        local schedule
        local done = Quark.Promise.New(function(resolve)
            schedule = Time.Schedule("* * * * * *", function(time)
                calls[#calls + 1] = time
                if #calls == 2 then
                    resolve()
                end
            end)
        end)
        Expect(schedule:IsActive()):ToBe(true)
        Expect(Time.IsDateTime(schedule:GetNext())):ToBe(true)
        Quark.Await(Quark.Promise.Race({ done, Quark.Delay(4000) }))
        schedule:Stop()

        Expect(#calls):ToBe(2)
        Expect(calls[2]:Since(calls[1])):ToBe(1000)
        Expect(calls[1].Millisecond):ToBe(0)
        Quark.Await(Quark.Delay(1300))
        Expect(#calls):ToBe(2)
        Expect(schedule:IsActive()):ToBe(false)
        Expect(schedule:GetNext()):ToBeNil()

        local invalid, message = Time.Schedule("nope", function() end)
        Expect(invalid):ToBeNil()
        Expect(message):ToContain("5 or 6 fields")
    end)
end)
