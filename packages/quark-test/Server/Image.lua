local Test = Quark.Import("Testing")
local Expect = Test.Expect

Test.Describe("Image", function()
    local Image = Quark.Image
    local base = Quark.Buffer.GetIndexBase()

    Test.It("creates images and parses colors", function()
        local image = Image.New(4, 3, "#336699")
        Expect({ image:GetSize() }):ToEqual({ 4, 3 })
        Expect({ image:GetPixel(base, base) }):ToEqual({ 0x33, 0x66, 0x99, 255 })
        image:SetPixel(base + 1, base, { 10, 20, 30 })
        Expect({ image:GetPixel(base + 1, base) }):ToEqual({ 10, 20, 30, 255 })
        image:SetPixel(base + 2, base, { R = 1, G = 0.5, B = 0, A = 1 })
        Expect({ image:GetPixel(base + 2, base) }):ToEqual({ 255, 128, 0, 255 })
        image:SetPixel(base + 3, base, "#f008")
        Expect({ image:GetPixel(base + 3, base) }):ToEqual({ 255, 0, 0, 136 })
        Expect(function() image:GetPixel(base + 9, base) end):ToThrow("outside of the image")
        Expect(function() image:Fill("purple") end):ToThrow("not a hex digit")
        Expect(function() Image.New(0, 1) end):ToThrow("between 1")
        Expect(Image.IsImage(image)):ToBe(true)
        Expect(#image:GetBytes()):ToBe(4 * 3 * 4)
    end)

    Test.It("draws shapes and blends images", function()
        local canvas = Image.New(20, 20, "#000000")
        canvas:FillRect(base, base, 5, 5, "#ff0000")
        Expect({ canvas:GetPixel(base + 4, base + 4) }):ToEqual({ 255, 0, 0, 255 })
        Expect({ canvas:GetPixel(base + 5, base + 5) }):ToEqual({ 0, 0, 0, 255 })
        canvas:DrawLine(base, base + 10, base + 19, base + 10, "#00ff00")
        Expect({ canvas:GetPixel(base + 15, base + 10) }):ToEqual({ 0, 255, 0, 255 })
        canvas:DrawCircle(base + 10, base + 15, 3, "#0000ff")
        Expect({ canvas:GetPixel(base + 10, base + 15) }):ToEqual({ 0, 0, 255, 255 })
        local overlay = Image.New(2, 2, "#ffffff")
        canvas:DrawImage(overlay, base + 18, base + 18, { Opacity = 0.5 })
        Expect({ canvas:GetPixel(base + 19, base + 19) }):ToEqual({ 128, 128, 128, 255 })
    end)

    Test.It("transforms images", function()
        local image = Image.New(4, 2, "#000000")
        image:SetPixel(base, base, "#ffffff")
        local rotated = image:Rotate(90)
        Expect({ rotated:GetSize() }):ToEqual({ 2, 4 })
        Expect({ rotated:GetPixel(base + 1, base) }):ToEqual({ 255, 255, 255, 255 })
        Expect({ image:Flip():GetPixel(base + 3, base) }):ToEqual({ 255, 255, 255, 255 })
        Expect({ image:Flip("Vertical"):GetPixel(base, base + 1) }):ToEqual({ 255, 255, 255, 255 })
        Expect({ image:Resize(8, 4, "Nearest"):GetSize() }):ToEqual({ 8, 4 })
        Expect({ image:Crop(base + 1, base, 10, 10):GetSize() }):ToEqual({ 3, 2 })
        local gray = Image.New(1, 1, "#ff0000"):Grayscale()
        local red, green, blue = gray:GetPixel(base, base)
        Expect(red == green and green == blue):ToBe(true)
        Expect({ Image.New(9, 9, "#ffffff"):Blur(1):GetSize() }):ToEqual({ 9, 9 })
        Expect(function() image:Rotate(45) end):ToThrow("90, 180 or 270")
    end)

    Test.It("encodes and decodes PNG, JPEG and WebP", function()
        local image = Image.New(16, 8, "#10a0f0")
        image:SetPixel(base, base, "#ff000080")
        local png = image:Encode("png")
        Expect(png:sub(2, 4)):ToBe("PNG")
        local decoded = assert(Image.Decode(png))
        Expect({ decoded:GetSize() }):ToEqual({ 16, 8 })
        Expect({ decoded:GetPixel(base, base) }):ToEqual({ 255, 0, 0, 128 })
        local jpeg = Quark.Await(image.Encode, image, "jpeg", { Quality = 90 })
        Expect(jpeg:byte(1)):ToBe(0xFF)
        local photo = Quark.Await(Image.Decode, jpeg)
        local red, green, blue = photo:GetPixel(base + 8, base + 4)
        Expect(math.abs(green - 0xa0) < 8):ToBe(true)
        Expect(assert(Image.Decode(image:Encode("webp"))):GetSize()):ToBe(16)
        Expect(select(2, Image.Decode("not an image"))):ToContain("cannot")
        Expect(function() image:Encode("tiff") end):ToThrow("unknown image format")
    end)

    Test.It("renders heights and tile maps", function()
        local heights = Image.FromHeights(2, 2, { 0, 50, 100, 25 }, { Colors = { { 0, "#0000ff" }, { 0.5, "#00ff00" }, { 1, "#ffffff" } } })
        Expect({ heights:GetPixel(base, base) }):ToEqual({ 0, 0, 255, 255 })
        Expect({ heights:GetPixel(base + 1, base) }):ToEqual({ 0, 255, 0, 255 })
        Expect({ heights:GetPixel(base, base + 1) }):ToEqual({ 255, 255, 255, 255 })
        local terrain = Quark.ProcGen.Heightmap(32, 32, { Seed = 1 })
        Expect({ Image.FromHeights(32, 32, terrain:View("f32")):GetSize() }):ToEqual({ 32, 32 })

        local map = Quark.ProcGen.Dungeon(40, 30, { Generator = Quark.Random.New(1) })
        local Tile = Quark.ProcGen.Tile
        local picture = Image.FromIndexed(40, 30, map:GetTiles(), { [Tile.Wall] = "#202020", [Tile.Floor] = "#c0c0c0", [Tile.Corridor] = "#909090", [Tile.Door] = "#a05000" })
        local room = map:GetRooms()[1]
        Expect({ picture:GetPixel(room.Center.X, room.Center.Y) }):ToEqual({ 0xc0, 0xc0, 0xc0, 255 })
        Expect(function() Image.FromIndexed(2, 2, { 1, 2 }, {}) end):ToThrow("expected 4 values")
    end)
end)
